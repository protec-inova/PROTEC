CREATE TABLE IF NOT EXISTS maquinas (
    id         UUID                     PRIMARY KEY,
    nome       VARCHAR(50)              NOT NULL,
    riscos     VARCHAR(255)             NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_maquinas_nome ON maquinas (nome);

CREATE TABLE IF NOT EXISTS funcionarios (
    id         UUID                     PRIMARY KEY,
    nome       VARCHAR(50)              NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_funcionarios_nome ON funcionarios (nome);


CREATE TABLE IF NOT EXISTS consentimentos (
    id             INTEGER                  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    funcionario_id UUID                     NOT NULL REFERENCES funcionarios (id),
    id_maquina     UUID                     NOT NULL REFERENCES maquinas (id),
    oculos         VARCHAR(20),
    bota           VARCHAR(20),
    data           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_consentimentos_funcionario ON consentimentos (funcionario_id);
CREATE INDEX IF NOT EXISTS ix_consentimentos_maquina ON consentimentos (id_maquina);
CREATE INDEX IF NOT EXISTS ix_consentimentos_data ON consentimentos (data);